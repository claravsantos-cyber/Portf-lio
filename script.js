const lightbox = document.getElementById("lightbox");
const lightboxImg = document.getElementById("lightbox-img");
const lightboxTag = document.getElementById("lightbox-tag");
const lightboxTitle = document.getElementById("lightbox-title");
const lightboxAuthor = document.getElementById("lightbox-author");
const lightboxDescription = document.getElementById("lightbox-description");
const lightboxCounter = document.getElementById("lightbox-counter");

const closeBtn = document.getElementById("close-btn");
const prevBtn = document.getElementById("prev-btn");
const nextBtn = document.getElementById("next-btn");

let currentIndex = 0;


function createCard(project, index) {

    const card = document.createElement("article");

    card.className = "project-card";

    card.innerHTML = `
        <img
            class="project-image"
            src="${project.image}"
            alt="${project.title}"
        >

        <div class="project-overlay">

            <div class="project-overlay-content">

                <span class="project-category">
                    ${project.category}
                </span>

                <h4 class="project-title">
                    ${project.title}
                </h4>

            </div>

        </div>
    `;

    card.addEventListener("click", () => {
        openLightbox(index);
    });

    return card;
}


function renderLesson(aula, galleryId) {

    const gallery = document.getElementById(galleryId);

    if (!gallery) {
        return;
    }

    const lessonProjects = projects.filter(
        project => project.aula === aula
    );

    lessonProjects.forEach(project => {

        const globalIndex = projects.indexOf(project);

        gallery.appendChild(
            createCard(project, globalIndex)
        );

    });
}


function openLightbox(index) {

    currentIndex = index;

    const project = projects[currentIndex];

    lightboxImg.src = project.image;
    lightboxImg.alt = project.title;

    lightboxTag.textContent = project.category;
    lightboxTitle.textContent = project.title;
    lightboxAuthor.textContent = project.author;
    lightboxDescription.textContent = project.description;

    lightboxCounter.textContent =
        `${currentIndex + 1} / ${projects.length}`;

    lightbox.classList.add("active");

    document.body.style.overflow = "hidden";
}


function closeLightbox() {

    lightbox.classList.remove("active");

    document.body.style.overflow = "";

}


function showPrevious() {

    currentIndex--;

    if (currentIndex < 0) {
        currentIndex = projects.length - 1;
    }

    openLightbox(currentIndex);
}


function showNext() {

    currentIndex++;

    if (currentIndex >= projects.length) {
        currentIndex = 0;
    }

    openLightbox(currentIndex);
}


closeBtn.addEventListener("click", closeLightbox);

prevBtn.addEventListener("click", showPrevious);

nextBtn.addEventListener("click", showNext);


lightbox.addEventListener("click", (event) => {

    if (event.target === lightbox) {
        closeLightbox();
    }

});


document.addEventListener("keydown", (event) => {

    if (!lightbox.classList.contains("active")) {
        return;
    }

    if (event.key === "Escape") {
        closeLightbox();
    }

    if (event.key === "ArrowLeft") {
        showPrevious();
    }

    if (event.key === "ArrowRight") {
        showNext();
    }

});


